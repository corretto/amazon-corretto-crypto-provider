package com.amazon.corretto.crypto.provider;

import java.security.InvalidKeyException;
import java.security.PublicKey;
import java.util.Arrays;

/**
 * An HPKE recipient public key. See {@link HpkeKey} for suite binding and encoding rules.
 *
 * @serial exclude
 */
public final class HpkePublicKey extends HpkeKey implements PublicKey {
  private final byte[] publicKey;

  /** Takes ownership of {@code publicKey}; callers must not modify it afterwards. */
  HpkePublicKey(final HpkeSuite suite, final byte[] publicKey) {
    super(suite);
    this.publicKey = Utils.requireNonNull(publicKey, "publicKey must not be null");
  }

  /**
   * Imports a defensive copy of the raw encoding described in {@link HpkeKey} for {@code spec}'s
   * suite ids. Info and encapsulation are ignored. Runs AWS-LC's encapsulation-key check (FIPS 203
   * section 7.2); keys generated by ACCP are valid by construction.
   *
   * @param spec the suite parameters
   * @param raw the raw public key bytes
   * @return the imported recipient public key
   * @throws InvalidKeyException if the suite is not one that the linked AWS-LC provides, or {@code
   *     raw} has the wrong length or is rejected by AWS-LC
   * @throws IllegalArgumentException if {@code spec} or {@code raw} is null
   */
  public static HpkePublicKey fromEncoded(final HpkeParameterSpec spec, final byte[] raw)
      throws InvalidKeyException {
    final HpkeSuite s = importSuite(spec);
    Utils.requireNonNull(raw, "raw must not be null");
    if (raw.length != s.publicKeyLength()) {
      throw new InvalidKeyException(
          "HPKE public key must be " + s.publicKeyLength() + " bytes for this suite");
    }
    // Check the copy that is stored, so a caller changing raw meanwhile cannot slip a bad key in.
    final byte[] copy = raw.clone();
    HpkeCipher.checkPublicKey(s, copy);
    return new HpkePublicKey(s, copy);
  }

  /** Returns a defensive copy of the raw public key bytes. */
  @Override
  public byte[] getEncoded() {
    return publicKey.clone();
  }

  /** Copy-free access for ACCP's own use. Callers must not modify the result. */
  byte[] getRawPublicKey() {
    return publicKey;
  }

  /** Compares HPKE public keys by suite and raw public key bytes. */
  @Override
  public boolean equals(final Object obj) {
    if (this == obj) {
      return true;
    }
    if (!(obj instanceof HpkePublicKey)) {
      return false;
    }
    final HpkePublicKey other = (HpkePublicKey) obj;
    return suite() == other.suite() && Arrays.equals(publicKey, other.publicKey);
  }

  /** Returns a hash based on the suite's KEM id and raw public key bytes. */
  @Override
  public int hashCode() {
    return 31 * suite().kemId + Arrays.hashCode(publicKey);
  }
}
